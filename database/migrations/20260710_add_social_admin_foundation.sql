MERGE INTO ROLE_DEFINITIONS target
USING (
  SELECT 'researcher' role_key, 'Researcher' display_name, 'Creates and manages research content' description, 1 is_system FROM dual
  UNION ALL SELECT 'student', 'Student', 'Participates in research discovery and discussion', 1 FROM dual
  UNION ALL SELECT 'librarian', 'Librarian', 'Manages scholarly metadata and author claims', 1 FROM dual
  UNION ALL SELECT 'moderator', 'Moderator', 'Triages reports and moderates content', 1 FROM dual
  UNION ALL SELECT 'admin', 'Administrator', 'Manages platform operations and users', 1 FROM dual
) source ON (target.role_key = source.role_key)
WHEN NOT MATCHED THEN INSERT (role_key, display_name, description, is_system)
VALUES (source.role_key, source.display_name, source.description, source.is_system);

MERGE INTO PERMISSION_DEFINITIONS target
USING (
  SELECT 'profile.manage' permission_key, 'Manage own profile' description FROM dual
  UNION ALL SELECT 'content.moderate', 'Review and change moderated content state' FROM dual
  UNION ALL SELECT 'users.manage', 'Suspend, activate, and inspect users' FROM dual
  UNION ALL SELECT 'roles.manage', 'Assign platform roles' FROM dual
  UNION ALL SELECT 'email_queue.manage', 'Inspect and retry email queue items' FROM dual
  UNION ALL SELECT 'analytics.view', 'View platform analytics' FROM dual
  UNION ALL SELECT 'audit.view', 'View audit records' FROM dual
) source ON (target.permission_key = source.permission_key)
WHEN NOT MATCHED THEN INSERT (permission_key, description)
VALUES (source.permission_key, source.description);
