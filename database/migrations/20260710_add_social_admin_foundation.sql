BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE RESEARCHER_PROFILES (
      user_id NUMBER PRIMARY KEY,
      slug VARCHAR2(100) NOT NULL UNIQUE,
      headline VARCHAR2(255),
      department VARCHAR2(150),
      position_title VARCHAR2(150),
      website_url VARCHAR2(500),
      orcid VARCHAR2(50),
      visibility VARCHAR2(20) DEFAULT 'public' NOT NULL
        CHECK (visibility IN ('public', 'network', 'private')),
      profile_completed_at TIMESTAMP,
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT fk_researcher_profiles_user FOREIGN KEY (user_id)
        REFERENCES USERS(user_id) ON DELETE CASCADE,
      CONSTRAINT uq_researcher_profiles_orcid UNIQUE (orcid)
    )
  ]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
