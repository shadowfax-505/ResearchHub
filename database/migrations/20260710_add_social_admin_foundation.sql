BEGIN
  FOR item IN (
    SELECT table_name FROM user_tables
    WHERE table_name IN ('RESEARCH_PAPERS', 'REVIEWS', 'QUESTIONS', 'ANSWERS')
  ) LOOP
    FOR column_to_add IN (
      SELECT 'STATUS' column_name, 'VARCHAR2(20) DEFAULT ''published'' NOT NULL CHECK (status IN (''draft'', ''published'', ''hidden'', ''removed'', ''pending_review''))' definition FROM dual
      UNION ALL SELECT 'VISIBILITY', 'VARCHAR2(20) DEFAULT ''public'' NOT NULL CHECK (visibility IN (''public'', ''network'', ''private''))' FROM dual
      UNION ALL SELECT 'DELETED_AT', 'TIMESTAMP' FROM dual
      UNION ALL SELECT 'DELETED_BY_USER_ID', 'NUMBER' FROM dual
    ) LOOP
      DECLARE
        column_count NUMBER;
      BEGIN
        SELECT COUNT(*) INTO column_count FROM user_tab_columns
        WHERE table_name = item.table_name AND column_name = column_to_add.column_name;
        IF column_count = 0 THEN
          EXECUTE IMMEDIATE 'ALTER TABLE ' || item.table_name || ' ADD (' || column_to_add.column_name || ' ' || column_to_add.definition || ')';
        END IF;
      END;
    END LOOP;
  END LOOP;
END;
