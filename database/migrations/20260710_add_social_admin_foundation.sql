    UNION ALL SELECT 'QUESTIONS', 'idx_questions_pub_state' FROM dual
    UNION ALL SELECT 'ANSWERS', 'idx_answers_pub_state' FROM dual
  ) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'CREATE INDEX ' || item.index_name || ' ON ' || item.table_name || ' (status, visibility, created_at)';
    EXCEPTION WHEN OTHERS THEN
