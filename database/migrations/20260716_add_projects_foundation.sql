-- PROJECTS is used by the API and PROJECT_UPDATES but was absent from a fresh install.
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE PROJECTS (
      project_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      user_id NUMBER NOT NULL,
      title VARCHAR2(300) NOT NULL,
      description CLOB,
      status VARCHAR2(20) DEFAULT 'active' NOT NULL CHECK (status IN ('active', 'completed', 'archived')),
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT fk_projects_owner FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
    )
  ]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX idx_projects_owner ON PROJECTS(user_id, created_at)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/
