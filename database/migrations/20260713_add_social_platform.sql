CREATE OR REPLACE PACKAGE BODY PKG_NETWORK AS
  PROCEDURE get_recommendations(p_user_id IN NUMBER, p_limit IN NUMBER, p_out OUT SYS_REFCURSOR) AS
  BEGIN
    OPEN p_out FOR SELECT * FROM (
      SELECT u.user_id, u.username, u.full_name, u.affiliation, u.country, u.profile_picture_url, rp.slug, rp.headline, rp.department, rp.position_title,
        (3 * (SELECT COUNT(*) FROM USER_DISCIPLINES a JOIN USER_DISCIPLINES b ON LOWER(a.discipline_name) = LOWER(b.discipline_name) WHERE a.user_id = p_user_id AND b.user_id = u.user_id)) +
        CASE WHEN LOWER(NVL(u.affiliation, '#')) = LOWER(NVL((SELECT affiliation FROM USERS WHERE user_id = p_user_id), '!')) THEN 4 ELSE 0 END +
        (2 * (SELECT COUNT(*) FROM PAPER_AUTHORS pa JOIN USER_AUTHOR_CLAIMS c1 ON c1.author_id = pa.author_id AND c1.user_id = p_user_id AND c1.status = 'verified' JOIN USER_AUTHOR_CLAIMS c2 ON c2.author_id = pa.author_id AND c2.user_id = u.user_id AND c2.status = 'verified')) +
        (SELECT COUNT(*) FROM USER_FOLLOWS f1 JOIN USER_FOLLOWS f2 ON f1.followed_user_id = f2.followed_user_id WHERE f1.follower_user_id = p_user_id AND f2.follower_user_id = u.user_id) score,
        CASE WHEN LOWER(NVL(u.affiliation, '#')) = LOWER(NVL((SELECT affiliation FROM USERS WHERE user_id = p_user_id), '!')) THEN 'same_institution'
          WHEN EXISTS (SELECT 1 FROM USER_DISCIPLINES a JOIN USER_DISCIPLINES b ON LOWER(a.discipline_name) = LOWER(b.discipline_name) WHERE a.user_id = p_user_id AND b.user_id = u.user_id) THEN 'shared_field'
          WHEN EXISTS (SELECT 1 FROM PAPER_AUTHORS pa JOIN USER_AUTHOR_CLAIMS c1 ON c1.author_id = pa.author_id AND c1.user_id = p_user_id AND c1.status = 'verified' JOIN USER_AUTHOR_CLAIMS c2 ON c2.author_id = pa.author_id AND c2.user_id = u.user_id AND c2.status = 'verified') THEN 'coauthor'
          ELSE 'similar_research' END recommendation_reason
      FROM USERS u JOIN RESEARCHER_PROFILES rp ON rp.user_id = u.user_id
      WHERE u.user_id <> p_user_id AND u.is_active = 1 AND u.account_status = 'active' AND rp.visibility = 'public'
        AND NOT EXISTS (SELECT 1 FROM USER_FOLLOWS f WHERE f.follower_user_id = p_user_id AND f.followed_user_id = u.user_id)
        AND NOT EXISTS (SELECT 1 FROM USER_BLOCKS b WHERE (b.blocker_user_id = p_user_id AND b.blocked_user_id = u.user_id) OR (b.blocker_user_id = u.user_id AND b.blocked_user_id = p_user_id))
      ORDER BY score DESC, u.user_id DESC
    ) WHERE ROWNUM <= NVL(p_limit, 20);
  END get_recommendations;
